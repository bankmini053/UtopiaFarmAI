def calibrate_camera_pitch():
    """
    ระบบตั้งศูนย์มุมมองกล้อง 3D (Pitch Calibration)
    - รอนิ่ง 5 วินาที
    - รูดขึ้นบนสุด 10 วินาที
    - รูดลงล่างสุด 10 วินาที
    - ดึงกลับมาระดับสายตากึ่งกลาง
    - หมุนกวาดสายตา 360 องศา
    """
    print("\n[🎯] เริ่มต้นกระบวนการตั้งศูนย์มุมกล้อง (Camera Calibration)...")
    
    # 1. รอ 5 วินาทีเมื่อเข้าเกม
    for sec in range(5, 0, -1):
        print(f"[*] กำลังตรวจสอบหน้าจอและเตรียมความพร้อม... เหลือ {sec} วินาที")
        time.sleep(1.0)

    center_x = 900  # พื้นที่ว่างฝั่งขวาจอสำหรับควบคุมมุมกล้อง

    # 2. เลื่อนหน้าจอขึ้นไปจนสุดเรื่อยๆ ประมาณ 10 วินาที (ก้มหน้า/แหงนสุดขอบบน)
    print("[*] กำลังปรับมุมกล้องขึ้นจนสุด (10 วินาที)...")
    start_time = time.time()
    while time.time() - start_time < 10.0:
        # ปัดจากกลางจอลงล่าง หรือ ปัดขึ้น เพื่อดันกล้องไปชนขอบสุด
        swipe_screen(center_x, 250, center_x, 500, duration=180)
        time.sleep(0.08)

    # หยุดนิ่งเพื่อวิเคราะห์
    print("[*] ชนขอบบนสุดแล้ว -> หยุดนิ่งสนิท 0.8 วินาทีเพื่อวิเคราะห์...")
    time.sleep(0.8)

    # 3. เลื่อนหน้าจอลงล่างสุดเรื่อยๆ ประมาณ 10 วินาที
    print("[*] กำลังปรับมุมกล้องลงจนสุด (10 วินาที)...")
    start_time = time.time()
    while time.time() - start_time < 10.0:
        swipe_screen(center_x, 500, center_x, 250, duration=180)
        time.sleep(0.08)

    # หยุดนิ่งเพื่อคำนวณกึ่งกลาง
    print("[*] ชนขอบล่างสุดแล้ว -> หยุดนิ่งคำนวณจุดกึ่งกลางสายตา...")
    time.sleep(0.8)

    # 4. คำนวณดึงมุมกล้องกลับมาอยู่กึ่งกลางระดับสายตา
    # (ปัดกลับขึ้นมาครึ่งหนึ่งของระยะขอบสุดเพื่อให้ได้ระนาบ 0 องศา)
    print("[✓] ปรับมุมกล้องกลับมาสู่ 'ระดับสายตากึ่งกลาง' เรียบร้อย!")
    for _ in range(6):
        swipe_screen(center_x, 250, center_x, 430, duration=190)
        time.sleep(0.1)

    time.sleep(0.5)

    # 5. หมุนกวาดกล้อง 360 องศา (8 ทิศทาง)
    print("[🔄] เริ่มต้นหมุนกล้องกวาดสายตา 360 องศา...")
    for turn_idx in range(8):
        print(f"[*] กวาดมุมมองรอบตัว ทิศที่ {turn_idx + 1}/8...")
        rotate_view_right(dist=180)
        time.sleep(0.4)

    print("[✨] การตั้งศูนย์มุมมองเสร็จสมบูรณ์ 100% พร้อมเริ่มค้นหาแร่!")
  
